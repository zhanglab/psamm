import gzip
import os
import shutil
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from psamm.datasource import chebi


def write_gzip_tsv(path, lines):
    with gzip.open(path, 'wt', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


CHEMICAL_DATA = [
    'id\tcompound_id\tformula\tcharge\tmass\tmonoisotopic_mass\t'
    'status_id\tstructure_id\tis_autogenerated',
    '12414\t15422\tC10H16N5O13P3\t0\t507.182\t506.99575\t1\t141\ttrue',
    '20039\t30616\tC10H12N5O13P3\t-4\t503.150\t502.96664\t1\t13653\ttrue',
    '99999\t12345\tC2H4\t\t28.05\t28.0313\t1\t1\ttrue',
]

SECONDARY_IDS = [
    'compound_id\tsecondary_id',
    '15422\t2359',
]


class TestChebiDb(unittest.TestCase):
    def setUp(self):
        self._dir = tempfile.mkdtemp()
        self._chemical_data = os.path.join(self._dir, chebi.CHEMICAL_DATA_FILE)
        self._secondary_ids = os.path.join(self._dir, chebi.SECONDARY_IDS_FILE)
        write_gzip_tsv(self._chemical_data, CHEMICAL_DATA)
        write_gzip_tsv(self._secondary_ids, SECONDARY_IDS)
        self.db = chebi.ChebiDb(self._chemical_data, self._secondary_ids)

    def tearDown(self):
        shutil.rmtree(self._dir)

    def test_length(self):
        self.assertEqual(len(self.db), 3)

    def test_get_charge_and_formula(self):
        self.assertEqual(self.db.get_charge('30616'), -4)
        self.assertEqual(self.db.get_formula('30616'), 'C10H12N5O13P3')
        self.assertEqual(self.db.get_charge('15422'), 0)

    def test_id_with_prefix_and_int(self):
        self.assertEqual(self.db.get_charge('CHEBI:30616'), -4)
        self.assertEqual(self.db.get_charge(30616), -4)
        self.assertIn('CHEBI:15422', self.db)

    def test_secondary_id(self):
        self.assertEqual(self.db.primary_id('2359'), '15422')
        self.assertEqual(self.db.get_formula('2359'), 'C10H16N5O13P3')
        self.assertIn('2359', self.db)

    def test_missing_charge(self):
        self.assertIsNone(self.db.get_charge('12345'))
        self.assertEqual(self.db.get_formula('12345'), 'C2H4')

    def test_unknown_id(self):
        self.assertNotIn('1', self.db)
        self.assertIsNone(self.db.get_charge('1'))
        self.assertIsNone(self.db.get_formula('1'))

    def test_without_secondary_ids(self):
        db = chebi.ChebiDb(self._chemical_data)
        self.assertEqual(db.get_charge('15422'), 0)
        self.assertIsNone(db.get_charge('2359'))


class TestChebiDownload(unittest.TestCase):
    def setUp(self):
        # Serve the flat files from a local directory using a file:// URL
        self._source = tempfile.mkdtemp()
        self._cache = tempfile.mkdtemp()
        write_gzip_tsv(os.path.join(self._source, chebi.CHEMICAL_DATA_FILE),
                       CHEMICAL_DATA)
        write_gzip_tsv(os.path.join(self._source, chebi.SECONDARY_IDS_FILE),
                       SECONDARY_IDS)
        self._url = Path(self._source).as_uri() + '/'

    def tearDown(self):
        shutil.rmtree(self._source)
        shutil.rmtree(self._cache)

    def test_download_files(self):
        target = os.path.join(self._cache, 'chebi')
        chebi.download_files(target, url=self._url)
        self.assertEqual(sorted(os.listdir(target)), sorted(chebi.CHEBI_FILES))

    def test_existing_files_are_kept(self):
        path = os.path.join(self._cache, chebi.SECONDARY_IDS_FILE)
        write_gzip_tsv(path, ['compound_id\tsecondary_id'])
        chebi.download_files(self._cache, url=self._url)
        db = chebi.ChebiDb(
            os.path.join(self._cache, chebi.CHEMICAL_DATA_FILE), path)
        self.assertNotIn('2359', db)

        chebi.download_files(self._cache, update=True, url=self._url)
        db = chebi.ChebiDb(
            os.path.join(self._cache, chebi.CHEMICAL_DATA_FILE), path)
        self.assertIn('2359', db)

    def test_failed_download_leaves_no_file(self):
        with self.assertRaises(OSError):
            chebi.download_files(self._cache, url=self._url + 'missing/')
        self.assertEqual(os.listdir(self._cache), [])

    def test_load(self):
        with mock.patch.object(chebi, 'CHEBI_FLAT_FILE_URL', self._url):
            with mock.patch.dict(os.environ, {'PSAMM_CHEBI_DIR': self._cache}):
                db = chebi.load()
        self.assertEqual(db.get_charge('2359'), 0)

    def test_default_cache_dir(self):
        with mock.patch.dict(os.environ, {'PSAMM_CHEBI_DIR': '/a/b'}):
            self.assertEqual(chebi.default_cache_dir(), '/a/b')
        env = {k: v for k, v in os.environ.items() if k != 'PSAMM_CHEBI_DIR'}
        env['XDG_CACHE_HOME'] = '/cache'
        with mock.patch.dict(os.environ, env, clear=True):
            self.assertEqual(chebi.default_cache_dir(),
                             os.path.join('/cache', 'psamm', 'chebi'))


if __name__ == '__main__':
    unittest.main()
